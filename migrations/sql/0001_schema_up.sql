-- Each checker validates one (version[, factor]) and the trigger runs it for OLD and NEW,
-- so moving a row between versions also re-checks the version it left.

-- formula_weight: the weights of a version sum to 1
CREATE FUNCTION check_formula_weights_of(v uuid) RETURNS void LANGUAGE plpgsql AS $$
DECLARE total numeric; factors int; active boolean;
BEGIN
  SELECT sum(weight), count(*) INTO total, factors FROM formula_weight WHERE formula_version_id = v;
  SELECT status = 'active' INTO active FROM formula_version WHERE id = v;
  -- an active version has the five factors (D-034); a draft may be incomplete while it is being built
  IF COALESCE(active, false) AND factors <> 5 THEN
    RAISE EXCEPTION 'active formula version % has % of the 5 factor weights', v, factors USING ERRCODE = 'check_violation';
  END IF;
  IF total IS NOT NULL AND total <> 1 THEN
    RAISE EXCEPTION 'weights of formula version % sum to %, expected 1', v, total USING ERRCODE = 'check_violation';
  END IF;
END $$;
CREATE FUNCTION check_formula_weights() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN PERFORM check_formula_weights_of(OLD.formula_version_id); END IF;
  IF TG_OP <> 'DELETE' THEN PERFORM check_formula_weights_of(NEW.formula_version_id); END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER formula_weight_sum_one AFTER INSERT OR UPDATE OR DELETE ON formula_weight
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_formula_weights();

-- A status change re-checks the version's weights. Like every deferred rule here, it applies to the
-- final state at commit: check_formula_weights_of reads the current status and weights, not NEW.
CREATE FUNCTION check_activated_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM check_formula_weights_of(NEW.id);
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER formula_version_active_has_weights AFTER INSERT OR UPDATE OF status ON formula_version
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_activated_version();

-- Writers of one version's weights, levels and bands conflict on the version row: each write
-- touches it (a no-op UPDATE), so a second writer waits (READ COMMITTED, then re-checks with the
-- committed rows) or fails with a serialization error (REPEATABLE READ / SERIALIZABLE). Two
-- transactions can therefore never each pass the deferred check and together break the rule.
CREATE FUNCTION lock_formula_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    UPDATE formula_version SET id = id WHERE id = OLD.formula_version_id;
  END IF;
  IF TG_OP <> 'DELETE' THEN
    UPDATE formula_version SET id = id WHERE id = NEW.formula_version_id;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER formula_weight_lock_version AFTER INSERT OR UPDATE OR DELETE ON formula_weight
  FOR EACH ROW EXECUTE FUNCTION lock_formula_version();
CREATE TRIGGER formula_level_lock_version AFTER INSERT OR UPDATE OR DELETE ON formula_level
  FOR EACH ROW EXECUTE FUNCTION lock_formula_version();
CREATE TRIGGER formula_urgency_band_lock_version AFTER INSERT OR UPDATE OR DELETE ON formula_urgency_band
  FOR EACH ROW EXECUTE FUNCTION lock_formula_version();

-- formula_level: monotone by rank inside (version, factor) (A-10): rank 1 is the strongest level;
-- value never increases as rank grows. Additive bonuses (is_bonus, e.g. personal_data_bonus) are skipped.
CREATE FUNCTION check_formula_levels_of(v uuid, f text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE bad record;
BEGIN
  SELECT a.level_code AS weaker, b.level_code AS stronger INTO bad
  FROM formula_level a JOIN formula_level b
    ON a.formula_version_id = b.formula_version_id AND a.factor = b.factor AND a.rank > b.rank
  WHERE a.formula_version_id = v AND a.factor = f
    AND NOT a.is_bonus AND NOT b.is_bonus
    AND a.value > b.value
  LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'factor % of version % is not monotone: % > %', f, v, bad.weaker, bad.stronger
      USING ERRCODE = 'check_violation';
  END IF;
END $$;
CREATE FUNCTION check_formula_levels() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN PERFORM check_formula_levels_of(OLD.formula_version_id, OLD.factor); END IF;
  IF TG_OP <> 'DELETE' THEN PERFORM check_formula_levels_of(NEW.formula_version_id, NEW.factor); END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER formula_level_monotone AFTER INSERT OR UPDATE OR DELETE ON formula_level
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_formula_levels();

-- formula_urgency_band: min_score strictly decreases as urgency goes from 1 (critical) to 4 (low)
CREATE FUNCTION check_urgency_bands_of(v uuid) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM formula_urgency_band a JOIN formula_urgency_band b
      ON a.formula_version_id = b.formula_version_id AND a.urgency < b.urgency
    WHERE a.formula_version_id = v AND a.min_score <= b.min_score
  ) THEN
    RAISE EXCEPTION 'urgency bands of version % are not strictly decreasing', v USING ERRCODE = 'check_violation';
  END IF;
END $$;
CREATE FUNCTION check_urgency_bands() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN PERFORM check_urgency_bands_of(OLD.formula_version_id); END IF;
  IF TG_OP <> 'DELETE' THEN PERFORM check_urgency_bands_of(NEW.formula_version_id); END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER formula_urgency_band_decreasing AFTER INSERT OR UPDATE OR DELETE ON formula_urgency_band
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_urgency_bands();

-- finding: the instance belongs to the group's product. The check first touches the group and the
-- instance with a no-op UPDATE, so it write-conflicts with a concurrent product change: under READ
-- COMMITTED the later writer waits and re-checks committed rows; under REPEATABLE READ or
-- SERIALIZABLE it fails with a serialization error. A FOR SHARE lock alone is not enough there.
CREATE FUNCTION check_finding_product() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE finding_group SET id = id WHERE id = NEW.finding_group_id;
  UPDATE installed_software SET id = id WHERE id = NEW.installed_software_id;
  PERFORM 1 FROM finding_group g, installed_software s
   WHERE g.id = NEW.finding_group_id AND s.id = NEW.installed_software_id
     AND s.software_product_id = g.software_product_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'installed software % is not an instance of the product of group %',
      NEW.installed_software_id, NEW.finding_group_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER finding_same_product AFTER INSERT OR UPDATE ON finding
  DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_finding_product();

-- The other side: neither an instance nor a group may change product while it has findings.
CREATE FUNCTION check_product_locked() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.software_product_id IS DISTINCT FROM OLD.software_product_id AND EXISTS (
    SELECT 1 FROM finding f
     WHERE (TG_TABLE_NAME = 'installed_software' AND f.installed_software_id = NEW.id)
        OR (TG_TABLE_NAME = 'finding_group' AND f.finding_group_id = NEW.id)
  ) THEN
    RAISE EXCEPTION '% % has findings; its product cannot change', TG_TABLE_NAME, NEW.id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER installed_software_product_locked AFTER UPDATE OF software_product_id ON installed_software
  DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_product_locked();
CREATE CONSTRAINT TRIGGER finding_group_product_locked AFTER UPDATE OF software_product_id ON finding_group
  DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_product_locked();

-- A-5: a ticket_finding links a finding of the ticket's own group
CREATE FUNCTION check_ticket_finding_group() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- write-conflict with a concurrent group change (same technique as check_finding_product)
  UPDATE ticket SET id = id WHERE id = NEW.ticket_id;
  UPDATE finding SET id = id WHERE id = NEW.finding_id;
  PERFORM 1 FROM ticket t, finding f
   WHERE t.id = NEW.ticket_id AND f.id = NEW.finding_id AND f.finding_group_id = t.finding_group_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'finding % does not belong to the group of ticket %', NEW.finding_id, NEW.ticket_id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER ticket_finding_same_group AFTER INSERT OR UPDATE ON ticket_finding
  DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_ticket_finding_group();

-- ...and neither side can move to another group while linked
CREATE FUNCTION check_group_locked() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.finding_group_id IS DISTINCT FROM OLD.finding_group_id AND EXISTS (
    SELECT 1 FROM ticket_finding tf
     WHERE (TG_TABLE_NAME = 'ticket' AND tf.ticket_id = NEW.id)
        OR (TG_TABLE_NAME = 'finding' AND tf.finding_id = NEW.id)
  ) THEN
    RAISE EXCEPTION '% % is linked through ticket_finding; its group cannot change', TG_TABLE_NAME, NEW.id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER ticket_group_locked AFTER UPDATE OF finding_group_id ON ticket
  DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_group_locked();
CREATE CONSTRAINT TRIGGER finding_group_locked AFTER UPDATE OF finding_group_id ON finding
  DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION check_group_locked();

