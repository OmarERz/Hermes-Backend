-- index expression. This wrapper pins the dictionary and is declared IMMUTABLE, the usual pattern.
CREATE FUNCTION normalize_text(value text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
RETURN lower(regexp_replace(btrim(public.unaccent('public.unaccent'::regdictionary, value)), '\s+', ' ', 'g'));
