-- Current value of every parameter: highest version, or the catalog default if never changed.
CREATE VIEW setting_current AS
SELECT d.key AS setting_key,
       COALESCE(v.value, d.default_value) AS value,
       v.version,
       v.changed_at,
       v.changed_by,
       (v.id IS NULL) AS is_default
FROM setting_definition d
LEFT JOIN LATERAL (
  SELECT sv.* FROM setting_value sv WHERE sv.setting_key = d.key ORDER BY sv.version DESC LIMIT 1
) v ON true;

-- Current state of each finding (last transition; uuid v7 id breaks ties on equal timestamps).
CREATE VIEW finding_current AS
SELECT f.id AS finding_id,
       f.finding_group_id,
       f.installed_software_id,
       last.status,
       last.observed_version,
       last.changed_at AS status_changed_at,
       first_seen.detected_at,
       CASE WHEN last.status = 'fixed' THEN last.changed_at END AS fixed_at
FROM finding f
JOIN LATERAL (
  SELECT c.status, c.observed_version, c.changed_at
  FROM finding_status_change c WHERE c.finding_id = f.id
  ORDER BY c.changed_at DESC, c.id DESC LIMIT 1
) last ON true
LEFT JOIN LATERAL (
  SELECT min(c.changed_at) AS detected_at
  FROM finding_status_change c WHERE c.finding_id = f.id AND c.status = 'new'
) first_seen ON true;

-- Group state. INTERPRETATION:
--   active     some finding is current (new, persistent, reopened, no_data), on a live asset, and not suppressed
--   suppressed every current finding has an active suppression
--   fixed      no current finding remains and some ticket of the group is not closed (or none exists)
--   closed     no current finding remains and every ticket of the group is closed
CREATE VIEW finding_group_status AS
WITH per_group AS (
  SELECT g.id AS finding_group_id,
         count(*) FILTER (WHERE fc.status <> 'fixed' AND a.decommissioned_at IS NULL AND s.id IS NULL) AS current_unsuppressed,
         count(*) FILTER (WHERE fc.status <> 'fixed' AND a.decommissioned_at IS NULL AND s.id IS NOT NULL) AS current_suppressed
  FROM finding_group g
  LEFT JOIN finding_current fc ON fc.finding_group_id = g.id
  -- findings on decommissioned assets do not count (ARQ-03, EVA-08)
  LEFT JOIN installed_software i ON i.id = fc.installed_software_id
  LEFT JOIN asset a ON a.id = i.asset_id
  LEFT JOIN suppression s ON s.finding_id = fc.finding_id AND s.lifted_at IS NULL
  GROUP BY g.id
), tickets AS (
  SELECT finding_group_id, count(*) AS total, count(*) FILTER (WHERE status = 'closed') AS closed
  FROM ticket GROUP BY finding_group_id
)
SELECT p.finding_group_id,
       CASE
         WHEN p.current_unsuppressed > 0 THEN 'active'
         WHEN p.current_suppressed > 0 THEN 'suppressed'
         WHEN COALESCE(t.total, 0) > 0 AND t.total = t.closed THEN 'closed'
         ELSE 'fixed'
       END AS status
FROM per_group p LEFT JOIN tickets t USING (finding_group_id);

-- Per-CI score detail. INTERPRETATION: urgency is the most urgent band whose min_score the final
-- reaches; the floor applies when the CVE was in KEV, the CI was exposed and the unfloored value
-- (base + group adjustment + CI adjustment) stays below kev_exposed_floor; the blocked suggestion
-- is that unfloored value clamped to 0..100; raw value = 100 × S, rounded half up.
CREATE VIEW asset_score_detail AS
SELECT s.assessment_id,
       s.asset_id,
       s.base,
       s.final,
       band.urgency,
       CASE band.urgency WHEN 1 THEN 'critical' WHEN 2 THEN 'high' WHEN 3 THEN 'medium' WHEN 4 THEN 'low' END AS level,
       floor_calc.floor_applied,
       CASE WHEN floor_calc.floor_applied THEN floor_calc.unfloored END AS blocked_suggestion,
       round(a.factor_s * 100)::smallint AS raw_value
FROM asset_score s
JOIN assessment a ON a.id = s.assessment_id
JOIN formula_version fv ON fv.id = a.formula_version_id
CROSS JOIN LATERAL (
  -- integer arithmetic: three smallints can overflow before the 0..100 clamp
  SELECT greatest(0, least(100, s.base::integer + a.judge_adjustment + s.ci_adjustment)) AS unfloored,
         (COALESCE(a.raw_in_kev, false) AND COALESCE(s.snap_exposed, false)
          AND s.base::integer + a.judge_adjustment + s.ci_adjustment < fv.kev_exposed_floor) AS floor_applied
) floor_calc
LEFT JOIN LATERAL (
  SELECT b.urgency FROM formula_urgency_band b
  WHERE b.formula_version_id = a.formula_version_id AND s.final >= b.min_score
  ORDER BY b.urgency LIMIT 1
) band ON true;

-- Ticket score: highest final among its current CIs in the most recent assessment of its group.
-- Current CIs (EVA-08): findings linked to the ticket and not removed, whose state is not fixed,
-- on assets not decommissioned.
CREATE VIEW ticket_score AS
SELECT t.id AS ticket_id,
       latest.id AS assessment_id,
       top.final AS score,
       top.asset_id AS driving_asset_id
FROM ticket t
JOIN LATERAL (
  SELECT a.id FROM assessment a WHERE a.finding_group_id = t.finding_group_id
  ORDER BY a.assessed_at DESC, a.id DESC LIMIT 1
) latest ON true
LEFT JOIN LATERAL (
  SELECT s.asset_id, s.final
  FROM ticket_finding tf
  JOIN finding_current fc ON fc.finding_id = tf.finding_id AND fc.status <> 'fixed'
  JOIN installed_software i ON i.id = fc.installed_software_id
  JOIN asset ast ON ast.id = i.asset_id AND ast.decommissioned_at IS NULL
  JOIN asset_score s ON s.assessment_id = latest.id AND s.asset_id = i.asset_id
  WHERE tf.ticket_id = t.id AND tf.removed_at IS NULL
  ORDER BY s.final DESC, s.asset_id LIMIT 1
) top ON true;

-- Mitigation from the data, per group. INTERPRETATION: ranges match the group's product through
-- its CPE mapping (NVD or CNA vendor/product); the fixed version is version_end of a range whose
-- end is exclusive.
CREATE VIEW data_mitigation AS
SELECT g.id AS finding_group_id,
       g.cve_id,
       (SELECT array_agg(DISTINCT r.version_end ORDER BY r.version_end)
          FROM cve_affected_range r
          JOIN cpe_mapping m ON m.software_product_id = g.software_product_id
         WHERE r.cve_id = g.cve_id AND r.version_end IS NOT NULL AND r.end_inclusive IS FALSE
           AND ((r.source = 'nvd_cpe' AND r.vendor = m.nvd_vendor AND r.product = m.nvd_product)
             OR (r.source = 'cna_affected' AND r.vendor = m.cna_vendor AND r.product = m.cna_product))
       ) AS fixed_versions,
       k.required_action AS kev_required_action,
       k.due_date AS kev_due_date,
       (SELECT array_agg(w.text ORDER BY w.id) FROM cve_workaround w WHERE w.cve_id = g.cve_id) AS workarounds,
       (SELECT array_agg(DISTINCT ref.url ORDER BY ref.url)
          FROM cve_reference ref JOIN cve_reference_tag tag ON tag.reference_id = ref.id
         WHERE ref.cve_id = g.cve_id AND tag.tag IN ('Patch', 'Vendor Advisory')) AS patch_references,
       (SELECT array_agg(DISTINCT i.ioc_type || ':' || i.value)
          FROM ioc_cve ic JOIN ioc i ON i.id = ic.ioc_id WHERE ic.cve_id = g.cve_id) AS iocs
FROM finding_group g
LEFT JOIN kev_entry k ON k.cve_id = g.cve_id;

-- Inventory issues: software without mapping, and live CIs without exposure, classification,
-- owner or custodian.
CREATE VIEW inventory_issue AS
SELECT 'software_unmapped'::text AS issue, NULL::uuid AS asset_id, p.id AS software_product_id
FROM software_product p
WHERE NOT EXISTS (SELECT 1 FROM cpe_mapping m WHERE m.software_product_id = p.id)
UNION ALL
SELECT x.issue, a.id, NULL::uuid
FROM asset a
CROSS JOIN LATERAL (VALUES
  ('exposure_unknown', a.exposed IS NULL),
  ('unclassified', a.confidentiality = 'unclassified'),
  ('owner_missing', a.owner_person_id IS NULL),
  ('custodian_missing', a.custodian_team_id IS NULL)
) AS x(issue, applies)
WHERE a.decommissioned_at IS NULL AND x.applies;

-- Source health: last successful fetch and consecutive failures since then.
CREATE VIEW source_health AS
SELECT s.id AS source_id,
       last_ok.finished_at AS last_ok_at,
       (SELECT count(*) FROM source_fetch f
         WHERE f.source_id = s.id AND f.status <> 'ok'
           AND f.started_at > COALESCE(last_ok.started_at, '-infinity')) AS consecutive_failures
FROM source s
LEFT JOIN LATERAL (
  SELECT f.started_at, f.finished_at FROM source_fetch f
  WHERE f.source_id = s.id AND f.status = 'ok' ORDER BY f.started_at DESC LIMIT 1
) last_ok ON true;

-- Source reliability: confirmed vs refuted claims in the configured window (reliability.window_days).
CREATE VIEW source_reliability AS
WITH win AS (
  SELECT COALESCE((SELECT (value #>> '{}')::int FROM setting_current WHERE setting_key = 'reliability.window_days'), 180) AS days
)
SELECT s.id AS source_id,
       count(*) FILTER (WHERE c.status = 'confirmed') AS confirmed,
       count(*) FILTER (WHERE c.status = 'refuted') AS refuted
FROM source s
CROSS JOIN win
LEFT JOIN claim c ON c.source_id = s.id AND c.resolved_at >= now() - make_interval(days => win.days)
GROUP BY s.id;

-- Actor activity by sector and country, from mentions and victims of the same analysis.
CREATE VIEW actor_activity AS
SELECT m.actor_id,
       v.sector_code,
       v.country_code,
       count(DISTINCT na.story_id) AS stories,
       min(st.created_at) AS first_seen_at,
       max(st.created_at) AS last_seen_at
FROM news_actor_mention m
JOIN news_analysis na ON na.id = m.analysis_id
JOIN story st ON st.id = na.story_id
LEFT JOIN news_victim v ON v.analysis_id = m.analysis_id
GROUP BY m.actor_id, v.sector_code, v.country_code;

-- LLM usage per UTC day and agent.
CREATE VIEW llm_usage_daily AS
SELECT (created_at AT TIME ZONE 'UTC')::date AS usage_date,
       agent,
       count(*) AS reviews,
       sum(tokens_input) AS tokens_input,
       sum(tokens_cached) AS tokens_cached,
       sum(tokens_output) AS tokens_output,
       sum(tokens_reasoning) AS tokens_reasoning,
       sum(cost_usd) AS cost_usd
FROM llm_review
GROUP BY 1, 2;

-- Current judge ladder level (0 if it never changed).
CREATE VIEW judge_ladder_current AS
SELECT COALESCE((SELECT level FROM judge_ladder_change ORDER BY changed_at DESC, id DESC LIMIT 1), 0)::smallint AS level;

-- Story timeline: first and last article date and its URLs.
CREATE VIEW story_timeline AS
SELECT story_id,
       min(published_at) AS first_published_at,
       max(published_at) AS last_published_at,
       array_agg(canonical_url ORDER BY published_at) AS urls
FROM raw_article
WHERE story_id IS NOT NULL
GROUP BY story_id;

-- Remediation times (MTTR): detection -> ticket -> fix -> close, per finding and ticket.
CREATE VIEW remediation_time AS
SELECT fc.finding_id,
       tf.ticket_id,
       fc.detected_at,
       t.itop_created_at AS ticketed_at,
       fc.fixed_at,
       t.closed_at,
       t.itop_created_at - fc.detected_at AS time_to_ticket,
       fc.fixed_at - fc.detected_at AS time_to_fix,
       t.closed_at - fc.detected_at AS time_to_close
FROM finding_current fc
LEFT JOIN ticket_finding tf ON tf.finding_id = fc.finding_id
LEFT JOIN ticket t ON t.id = tf.ticket_id;
